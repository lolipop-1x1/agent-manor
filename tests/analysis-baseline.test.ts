import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdtemp, mkdir, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { promisify } from "node:util";
import { classifyFile, getRepository, scanRepository, textLines } from "../src/analysis/index.js";

const run = promisify(execFile);
async function git(path: string, ...args: string[]) {
  return run("git", ["-C", path, ...args]);
}

async function createRepository(t: test.TestContext) {
  const root = await mkdtemp(join(tmpdir(), "manor-analysis-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const repository = join(root, "repository");
  await mkdir(repository);
  await git(repository, "init", "-b", "main");
  await git(repository, "config", "user.name", "分析样本");
  await git(repository, "config", "user.email", "analysis@example.invalid");
  return { root, repository };
}

test("物理行包含空白与注释，末尾换行不产生额外行", () => {
  assert.deepEqual(textLines(""), []);
  assert.deepEqual(textLines("\n"), [""]);
  assert.equal(textLines("a\n\n// 注释\n").length, 3);
  assert.equal(textLines("a\r\n\r\n").length, 2);
  assert.equal(textLines("a\rb").length, 2);
  assert.equal(classifyFile("src/index.ts"), "source");
  assert.equal(classifyFile(".env.local"), "config");
  assert.equal(classifyFile("README"), "docs");
  assert.equal(classifyFile("data.custom"), "unknown");
});

test("当前基线包含未提交与未忽略未跟踪，排除删除、依赖、生成、二进制和符号链接", async (t) => {
  const { repository } = await createRepository(t);
  await mkdir(join(repository, "src"));
  await mkdir(join(repository, "dist"));
  await writeFile(join(repository, ".gitignore"), "ignored.ts\n");
  await writeFile(join(repository, "src", "tracked.ts"), "const tracked = 1;\n");
  await writeFile(join(repository, "deleted.ts"), "const deleted = 1;\n");
  await git(repository, "add", ".gitignore", "src/tracked.ts", "deleted.ts");
  await git(repository, "commit", "-m", "建立测试基线");
  await rm(join(repository, "deleted.ts"));
  await writeFile(join(repository, "src", "tracked.ts"), "const tracked = 2;\n\n");
  await writeFile(join(repository, "untracked.ts"), "const untracked = true;");
  await writeFile(join(repository, "ignored.ts"), "const ignored = true;");
  await writeFile(join(repository, "dist", "bundle.js"), "const generated = true;");
  await writeFile(join(repository, "generated.go"), "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n");
  await writeFile(join(repository, "binary.dat"), Buffer.from([0, 1, 2]));
  await writeFile(join(repository, "invalid.dat"), Buffer.from([0xff]));
  await writeFile(join(repository, "notes.custom"), "未知类别\n");
  await writeFile(join(repository, "empty.ts"), "");
  await symlink("src/tracked.ts", join(repository, "linked.ts"));
  const baseline = await scanRepository(repository);
  assert.equal(baseline.git.dirty, true);
  assert.equal(baseline.git.branch, "main");
  assert.equal(baseline.files.find((file) => file.path === "src/tracked.ts")?.lineCount, 2);
  assert.equal(baseline.files.find((file) => file.path === "src/tracked.ts")?.content, "const tracked = 2;\n\n");
  assert.equal(baseline.files.find((file) => file.path === "notes.custom")?.category, "unknown");
  assert.equal(baseline.files.find((file) => file.path === "empty.ts")?.lineCount, 0);
  assert.equal(baseline.files.some((file) => file.path === "untracked.ts"), true);
  assert.equal(baseline.files.some((file) => file.path === "ignored.ts"), false);
  const excluded = new Map(baseline.excluded.map((file) => [file.path, file.reason]));
  assert.equal(excluded.get("deleted.ts"), "deleted_from_worktree");
  assert.equal(excluded.get("linked.ts"), "symlink_not_followed");
  assert.equal(excluded.get("dist/bundle.js"), "dependency_or_generated_directory");
  assert.equal(excluded.get("generated.go"), "generated_header");
  assert.equal(excluded.get("binary.dat"), "binary_or_non_utf8");
  assert.equal(excluded.get("invalid.dat"), "binary_or_non_utf8");
  const unchanged = await scanRepository(repository);
  assert.equal(unchanged.hash, baseline.hash);
  await writeFile(join(repository, "src", "tracked.ts"), "const tracked = 3;\n\n");
  assert.notEqual((await scanRepository(repository)).hash, baseline.hash);
});

test("父目录变为符号链接时不盘点链接指向的源码", async (t) => {
  const { root, repository } = await createRepository(t);
  const outside = join(root, "outside");
  await mkdir(outside);
  await mkdir(join(repository, "nested"));
  await writeFile(join(repository, "nested", "escape.ts"), "const original = 1;\n");
  await git(repository, "add", "nested/escape.ts");
  await rm(join(repository, "nested"), { recursive: true });
  await writeFile(join(outside, "escape.ts"), "const external = 1;\n");
  await symlink(outside, join(repository, "nested"));
  const baseline = await scanRepository(repository);
  assert.equal(baseline.files.length, 0);
  assert.equal(baseline.excluded.find((file) => file.path === "nested/escape.ts")?.reason, "symlink_not_followed");
});

test("worktree 共享 commonDir 但身份与基线独立，clone 与子模块各自独立", async (t) => {
  const { root, repository } = await createRepository(t);
  await writeFile(join(repository, "main.ts"), "const main = true;\n");
  await git(repository, "add", "main.ts");
  await git(repository, "commit", "-m", "建立测试基线");
  const worktree = join(root, "worktree");
  const clone = join(root, "clone");
  await git(repository, "worktree", "add", "-b", "fixture", worktree);
  await git(root, "clone", repository, clone);
  const [originalIdentity, worktreeIdentity, cloneIdentity] = await Promise.all([
    getRepository(repository), getRepository(worktree), getRepository(clone),
  ]);
  assert.equal(originalIdentity.commonDir, worktreeIdentity.commonDir);
  assert.notEqual(originalIdentity.id, worktreeIdentity.id);
  assert.notEqual(originalIdentity.commonDir, cloneIdentity.commonDir);
  assert.notEqual(originalIdentity.id, cloneIdentity.id);
  await writeFile(join(worktree, "main.ts"), "const worktree = true;\n");
  assert.notEqual((await scanRepository(repository)).hash, (await scanRepository(worktree)).hash);
  await git(repository, "-c", "protocol.file.allow=always", "submodule", "add", clone, "modules/child");
  const parent = await scanRepository(repository);
  assert.equal(parent.excluded.find((file) => file.path === "modules/child")?.reason, "submodule_independent_repository");
  assert.equal(parent.files.some((file) => file.path.startsWith("modules/child/")), false);
  assert.equal((await scanRepository(join(repository, "modules", "child"))).files.some((file) => file.path === "main.ts"), true);
});
