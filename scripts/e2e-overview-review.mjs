import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { weeklyReviewFixture } from "./weekly-review-fixture.mjs";

// 浏览器交互、延迟和价格均只针对隔离合成后台。
const run = promisify(execFile), fixture = await weeklyReviewFixture();
const artifacts = fileURLToPath(new URL("../.local/overview-review-e2e/", import.meta.url));
const session = `overview-review-${process.pid}`;
let opened = false;
const browser = async args => {
  const { stdout } = await run("playwright-cli", [`-s=${session}`, ...args], { cwd: fixture.directory, env: { ...process.env, TMPDIR: "/tmp" }, timeout: 60_000, maxBuffer: 4 * 1024 * 1024 });
  if (stdout.includes("### Error")) throw new Error(stdout);
  return stdout;
};
try {
  const started = performance.now(), response = await fetch(`${fixture.base}/api/v1/overview/review`), review = await response.json();
  assert.equal(response.status, 200, JSON.stringify(review));
  assert.equal(review.sessions.active, 4); assert.equal(review.sessions.compressions, 1);
  assert.equal(review.rounds.completed, 161); assert.equal(review.cache.requests, 336);
  assert.equal(review.extensions.children.sessions, 1); assert.ok(review.rounds.steps.average > 0);
  assert.ok(review.rounds.durationMs.average > 0); assert.ok(review.preferences.promptCharacters.average > 0);
  assert.equal(review.preferences.agents.length, 2); assert.equal(review.preferences.reasoning.length, 2);
  await mkdir(artifacts, { recursive: true });
  await writeFile(`${artifacts}/api-summary.json`, JSON.stringify({ review, coldMs: performance.now() - started }, null, 2));
  await browser(["open", `${fixture.base}/#overview`, "--headed", "--browser=chrome"]); opened = true;
  const verify = async (page, options) => {
    const checks = [], errors = []; page.on("pageerror", error => errors.push(error.message));
    const ensure = (value, description) => { if (!value) throw new Error(description); checks.push(description); };
    const button = name => page.getByRole("button", { name, exact: true });
    const choose = async (name, value) => { await page.getByRole("combobox", { name, exact: true }).click(); await page.getByRole("option", { name: value, exact: true }).click(); };
    const ready = async () => { await page.locator(".weekly-review[aria-busy='false'] .weekly-review-groups").waitFor(); await page.locator(".overview-results[aria-busy='false']").waitFor(); };
    const metric = name => page.locator(".weekly-review-metric").filter({ has: page.getByText(name, { exact: true }) });
    const detailReady = async () => { await page.locator(".weekly-review-dialog .overview-investigation-body[aria-busy='false']").waitFor(); };
    await page.setViewportSize({ width: 1440, height: 1000 }); await ready();
    let releaseSnapshot; const snapshotGate = new Promise(resolve => { releaseSnapshot = resolve; });
    await page.route("**/api/v1/overview/snapshot?**", async route => { await snapshotGate; await route.continue(); });
    await page.goto(`${options.base}/?review-cold=1#overview?window=all`);
    await page.locator(".weekly-review[aria-busy='false'] .weekly-review-groups").waitFor();
    ensure(await page.locator(".overview-results").count() === 0, "年度快照未返回时固定七天仍能先呈现");
    await metric("平均模型步骤").click(); await detailReady();
    ensure(await page.locator(".weekly-review-distribution tbody tr").count() === 4, "年度快照等待期间复盘详情独立可用");
    await page.keyboard.press("Escape"); releaseSnapshot(); await ready(); await page.unroute("**/api/v1/overview/snapshot?**");
    ensure(await page.locator(".weekly-review-group").count() === 4 && await page.locator(".weekly-review-metric").count() === 18, "四组18项核心数值齐全");
    ensure((await metric("活跃用户会话").innerText()).endsWith("4"), "活跃会话排除子Agent");
    ensure((await metric("已结束轮次").innerText()).endsWith("161"), "明确结束轮次与API一致");
    ensure((await metric("平均提示词字数").innerText()).includes("23"), "提示词均值显示真实合成字符数");
    ensure(await page.getByText("重点洞察", { exact: true }).count() === 0, "旧重点洞察已替换");
    const heldRange = await page.locator(".weekly-review-range").innerText();
    let reviewReads = 0; const count = req => { if (/\/api\/v1\/overview\/review\?/.test(req.url())) reviewReads++; }; page.on("request", count);
    let releasePanels; const panelGate = new Promise(resolve => { releasePanels = resolve; });
    await page.route("**/api/v1/overview/panel?**", async route => { await panelGate; await route.continue(); });
    await choose("日期范围", "近 30 天");
    await page.locator(".overview-results[aria-busy='true']").waitFor();
    ensure(await metric("平均模型步骤").evaluate(el => !el.closest("[inert]")), "仅改变顶部日期不会暂停固定七天交互");
    await metric("平均模型步骤").click(); await detailReady();
    ensure(await page.locator(".weekly-review-distribution tbody tr").count() === 4, "日期面板更新期间固定七天详情可立即打开");
    await page.keyboard.press("Escape"); releasePanels(); await ready(); await page.unroute("**/api/v1/overview/panel?**");
    ensure(await page.locator(".weekly-review-range").innerText() === heldRange && reviewReads === 0, "顶部日期不改变或重读固定七天");
    await metric("平均模型步骤").click(); await detailReady();
    ensure(await page.locator(".weekly-review-distribution tbody tr").count() === 4, "轮次详情提供步骤工具Token耗时分位数");
    await choose("排序", "耗时最长"); await detailReady();
    ensure((await page.locator(".weekly-review-records tbody tr").first().innerText()).includes("秒"), "最长轮次详情存在真实耗时");
    await page.locator(".weekly-review-record-title").first().click();
    await page.waitForFunction(() => location.hash.startsWith("#sessions?") && location.hash.includes("message="));
    await page.locator(".session-profile").waitFor();
    ensure(await page.locator(".session-profile").isVisible(), "轮次下钻定位会话原需求");
    await button("总览").click(); await detailReady();
    ensure(await page.locator(".weekly-review-dialog").count() === 1, "返回总览保留原详情");
    await page.keyboard.press("Escape"); await page.locator(".weekly-review-dialog").waitFor({ state: "hidden" });
    await ready();
    await metric("常用 Agent").click(); await detailReady();
    ensure(await page.locator(".weekly-review-ranks tbody tr").count() === 2, "Agent完整排行显示两个客户端");
    await page.locator(".weekly-review-ranks tbody tr").first().getByRole("button").first().click(); await detailReady();
    ensure(await page.locator(".weekly-review-ranks").count() === 0 && await button("返回").isVisible(), "客户端排行可过滤对应需求记录");
    await choose("复盘视图", "常用思考程度"); await detailReady();
    ensure(await page.locator(".weekly-review-ranks tbody tr").count() === 2, "思考程度排行保留明确设置");
    await choose("复盘视图", "压缩次数"); await detailReady();
    ensure(await page.locator(".weekly-review-ranks tbody tr").count() === 1, "压缩会话集中度有完整排行");
    await page.locator(".weekly-review-ranks tbody tr").first().getByRole("button").first().click(); await detailReady();
    ensure(await page.locator(".weekly-review-records tbody tr").count() === 1, "压缩会话下钻定位压缩事件");
    await choose("复盘视图", "无压缩会话平均峰值输入"); await detailReady();
    ensure(await page.locator(".weekly-review-records tbody tr").count() === 3, "无压缩峰值按合格会话取样");
    await choose("复盘视图", "用户提示词"); await detailReady();
    ensure((await page.locator(".weekly-review-distribution").innerText()).includes("23"), "提示词详情可看均值与覆盖");
    await choose("复盘视图", "用户交互集中时段"); await detailReady();
    ensure(await page.locator(".weekly-review-hour-bars > div").count() === 24 && await page.locator(".weekly-review-heatmap-row").count() === 7, "用户消息小时与星期热力图完整");
    await choose("复盘视图", "缓存请求"); await detailReady(); await choose("记录筛选", "缓存未知"); await detailReady();
    ensure((await page.locator(".weekly-review-records tbody tr").first().innerText()).includes("—"), "缺缓存字段保留未知而非零");
    await choose("复盘视图", "项目投入"); await detailReady();
    ensure(await page.locator(".weekly-review-ranks tbody tr").count() === 2, "项目投入有可下钻排行");
    await choose("复盘视图", "子 Agent 投入"); await detailReady();
    ensure(await page.locator(".weekly-review-records tbody tr").count() > 0, "子Agent投入单独可回查");
    await choose("复盘视图", "工具负担"); await detailReady();
    ensure(await page.locator(".weekly-review-records tbody tr").count() > 0, "工具明确失败与后续调用可回查");
    await page.keyboard.press("Escape"); await ready();
    const previous = await page.locator(".weekly-review-groups").innerHTML();
    let release; const gate = new Promise(resolve => { release = resolve; });
    await page.route("**/api/v1/overview/review?**", async route => { await gate; await route.continue(); });
    await button("更新总览").click(); await page.locator(".weekly-review[aria-busy='true']").waitFor();
    ensure(await page.locator(".weekly-review-groups").innerHTML() === previous, "更新期间保留上一份完整复盘");
    ensure(await page.locator(".weekly-review-groups").evaluate(el => !!el.closest("[inert]")), "更新期间暂停旧结果下钻");
    release(); await ready(); await page.unroute("**/api/v1/overview/review?**");
    page.off("request", count);
    await choose("客户端", "Claude Code"); await ready();
    ensure((await metric("活跃用户会话").innerText()).endsWith("1"), "客户端筛选改变周复盘");
    await choose("客户端", "全部客户端"); await ready();
    await button("项目").click(); await page.getByRole("combobox", { name: "项目搜索", exact: true }).fill("beta");
    await page.getByRole("option", { name: /beta/ }).click(); await ready();
    ensure((await metric("活跃用户会话").innerText()).endsWith("2"), "项目筛选同步固定周复盘");
    await button("项目").click(); await page.getByRole("option", { name: "全部项目", exact: true }).click(); await ready();
    await page.locator(".weekly-review").scrollIntoViewIfNeeded(); await page.screenshot({ path: `${options.artifacts}/desktop-zh.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "窄屏复盘没有整页横向溢出");
    await metric("平均模型步骤").click(); await detailReady();
    ensure(await page.locator(".weekly-review-dialog").evaluate(el => el.getBoundingClientRect().right <= innerWidth), "窄屏详情保持视口内");
    await page.keyboard.press("Escape");
    await button("显示语言").click(); await page.getByRole("menuitemradio", { name: "English", exact: true }).click();
    await page.getByRole("heading", { name: "Last 7 days in review", exact: true }).waitFor();
    await button("Appearance").click(); await choose("Display mode", "Dark"); await page.keyboard.press("Escape");
    await metric("Average model steps").click(); await detailReady();
    ensure((await page.locator(".weekly-review-distribution").innerText()).includes("Eligible samples"), "英文详情样本和分位数翻译完整");
    await page.screenshot({ path: `${options.artifacts}/mobile-dark-en-details.png`, fullPage: true });
    await page.keyboard.press("Escape");
    await page.locator(".weekly-review-dialog").waitFor({ state: "hidden" });
    await page.waitForFunction(() => document.activeElement?.classList.contains("weekly-review-metric"));
    ensure(await metric("Average model steps").evaluate(el => el === document.activeElement), "详情关闭恢复原指标焦点");
    await page.screenshot({ path: `${options.artifacts}/mobile-dark-en.png`, fullPage: true });
    ensure(errors.length === 0, `浏览器无运行错误：${errors.join(';')}`);
    return { passed: true, checks, errors };
  };
  const output = await browser(["run-code", `async page => (${verify.toString()})(page, ${JSON.stringify({ artifacts, base: fixture.base })})`]);
  console.log(output.split("### Ran Playwright code")[0]); await writeFile(`${artifacts}/result.txt`, output);
  assert.match(output, /"passed"\s*:\s*true/, "最近七天复盘验收未通过");
} finally { if (opened) await browser(["close"]).catch(() => undefined); await fixture.close(); }
